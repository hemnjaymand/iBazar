type CategoryUrlInput = {
  slug?: string | null;
  id: string;
};

/**
 * تابع متمرکز ساخت آدرس دسته‌بندی — این آدرس باید دقیقاً با مسیر واقعی
 * صفحه (app/(shop)/[categorySlug]/page.tsx) یکی باشه. اون صفحه هیچ
 * پیشوندی مثل "/category" نداره، پس این‌جا هم نباید اضافه بشه.
 */
export function getCategoryUrl(category: CategoryUrlInput): string {
  const target = category.slug?.trim() || category.id;
  return `/${target}`;
}

//توضیح برای یادگیری
// در طراحی اپلیکیشن‌های وب مدرن، داشتن یک تابع متمرکز (Utility Function) برای ساخت URLها یکی از بهترین الگوها برای جلوگیری از تکرار کد (DRY) است.

// این تابع یک سناریوی بسیار رایج را به خوبی مدیریت می‌کند: گاهی ممکن است یک دسته‌بندی در دیتابیس slug نداشته باشد یا مقدار آن خالی ثبت شده باشد. اگر فرانت‌اند مستقیماً از category.slug استفاده کند، لینک نهایی خراب می‌شود. این تابع با استفاده از عملگر منطقی (||) و چک کردن وجود slug، تضمین می‌کند که برنامه‌ی شما همیشه یک شناسه‌ی معتبر برای لینک‌دهی در اختیار دارد.